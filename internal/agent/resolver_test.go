package agent

import (
	"strings"
	"testing"
)

// TestResolverConf: the drop-in names the servers in order, after a line
// saying where it comes from.
func TestResolverConf(t *testing.T) {
	got := resolverConf([]string{"192.168.1.10:5053", "9.9.9.9:53"})
	if !strings.HasPrefix(got, "# Generated by roostack-agent") || !strings.HasSuffix(got, "[Resolve]\nDNS=192.168.1.10:5053 9.9.9.9:53\n") {
		t.Errorf("drop-in:\n%s", got)
	}
	if (ResolverRequest{Servers: []string{"1.1.1.1:53", "1.0.0.1:53", "9.9.9.9:53", "8.8.8.8:53"}}).Validate() == nil {
		t.Error("four servers accepted")
	}
}
