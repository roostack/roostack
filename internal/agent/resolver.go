package agent

import (
	"errors"
	"fmt"
	"net/netip"
	"os"
	"os/exec"
	"strings"

	"roostack.cloud/roostack/internal/fsutil"
)

// The lab's DNS server for this server's own lookups, when the Owner
// chooses it (SPEC.md §6.5.2): a drop-in for systemd-resolved, which
// Debian's cloud images use, adding it ahead of the servers the network
// gives, which stay for when it doesn't answer.

// ResolverRequest is the DNS servers this server's own lookups use first,
// as address:port; none puts its own back.
type ResolverRequest struct {
	Servers []string `json:"servers"`
}

// Validate checks the request: at most three IPv4 servers with ports.
func (r ResolverRequest) Validate() error {
	if len(r.Servers) > 3 {
		return errors.New("servers: at most three")
	}
	for i, s := range r.Servers {
		if ap, err := netip.ParseAddrPort(s); err != nil || !ap.Addr().Is4() || ap.Port() == 0 {
			return fmt.Errorf("servers[%d]: an IPv4 address and port, such as 192.168.1.2:53", i)
		}
	}
	return nil
}

// ResolverFile is the drop-in the agent writes.
var ResolverFile = "/etc/systemd/resolved.conf.d/roostack.conf"

// resolverConf is the drop-in for servers.
func resolverConf(servers []string) string {
	return "# Generated by roostack-agent: the lab's DNS server, chosen in Roostack's\n" +
		"# Settings, Where it is and DNS. Do not edit: changes will be overwritten.\n" +
		"[Resolve]\nDNS=" + strings.Join(servers, " ") + "\n"
}

// SetResolver writes the drop-in, or removes it for none, and restarts
// systemd-resolved when it changed. A server without systemd-resolved is
// refused rather than have its /etc/resolv.conf rewritten.
func (h LinuxHost) SetResolver(r ResolverRequest) error {
	old, err := os.ReadFile(ResolverFile)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	active := exec.Command("systemctl", "is-active", "--quiet", "systemd-resolved").Run() == nil
	if len(r.Servers) == 0 {
		if old == nil {
			return nil
		}
		if err := os.Remove(ResolverFile); err != nil {
			return err
		}
	} else {
		if !active {
			return errors.New("this server doesn't use systemd-resolved, so Roostack can't set its DNS server")
		}
		want := resolverConf(r.Servers)
		if string(old) == want {
			return nil
		}
		if err := fsutil.WriteFile(ResolverFile, []byte(want), 0o644); err != nil {
			return err
		}
	}
	if !active {
		return nil
	}
	if out, err := exec.Command("systemctl", "restart", "systemd-resolved").CombinedOutput(); err != nil {
		return fmt.Errorf("restarting systemd-resolved: %w: %s", err, out)
	}
	return nil
}
